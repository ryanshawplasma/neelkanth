/** Round to a shubh price ending in 1 (₹501, ₹851, ₹1,251 …). */
const shubh = (n: number) => Math.max(51, Math.round(n / 50) * 50 + 1);
/** Struck-through "compare at" price, ~35% above the real one. */
const cmp = (n: number) => shubh(n * 1.35);

const img = (slug: string) => [`/images/services/${slug}.svg`, `/images/services/${slug}-alt.svg`];

