/**
 * The service catalogue — online poojas, chadhava, pandit-at-home rituals,
 * astrology, prasad, katha and live darshan.
 *
 * Everything here is plain TypeScript so it can be imported both by
 * `prisma/seed.ts` and by `scripts/generate-art.ts` without pulling in Prisma.
 *
 * Conventions
 * - `templeSlug` must exist in `./temples`, `categorySlug` in `./categories`,
 *   `festivalSlug` in `./festivals` (MAJOR_FESTIVALS slugs include the year).
 * - Prices are whole rupees. `basePrice` is always the cheapest package.
 * - `nextDate` is the next auspicious performance date after 2026-09-10:
 *   Mondays for Shiva, Tuesdays/Saturdays for Hanuman and Shani, Fridays for
 *   Devi and Lakshmi, Ekadashi for Vishnu, and the linked festival date for
 *   occasion poojas.
 * - Artwork lives at `/images/services/<slug>.svg` (+ an `-alt` variant),
 *   generated by `scripts/generate-art.ts`. Admins can replace it with real
 *   photographs from the admin console — see docs/IMAGES.md.
 */
